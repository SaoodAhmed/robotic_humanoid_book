def embed(texts: List[str]) -> List[List[float]]:
    """
    [US3] Implement embed function to generate vector embeddings from text
    """
    cohere_api_key = os.getenv('COHERE_API_KEY')
    if not cohere_api_key:
        raise ValueError("COHERE_API_KEY environment variable not set")

    co = cohere.Client(cohere_api_key)

    try:
        response = co.embed(
            texts=texts,
            model=os.getenv('EMBEDDING_MODEL', 'embed-multilingual-v3.0'),  # Balanced cost/performance
            input_type="search_document"
        )

        return response.embeddings
    except Exception as e:
        logger.error(f"Error generating embeddings: {e}")
        raise


def create_qdrant_collection(client: QdrantClient, collection_name: str = "rag_embeddings"):
    """
    [US3] Create Qdrant collection named "rag_embeddings" with proper schema
    """
    try:
        # Check if collection already exists
        collections = client.get_collections()
        existing_collections = [c.name for c in collections.collections]

        if collection_name in existing_collections:
            logger.info(f"Collection '{collection_name}' already exists")
            return

        # Create new collection
        client.create_collection(
            collection_name=collection_name,
            vectors_config=models.VectorParams(
                size=1024,  # Cohere embed-multilingual-v3.0 returns 1024-dim vectors
                distance=models.Distance.COSINE
            )
        )

        logger.info(f"Created collection '{collection_name}' with 1024-dim vectors")
    except Exception as e:
        logger.error(f"Error creating collection: {e}")
        raise


def save_chunk_to_qdrant(client: QdrantClient, collection_name: str, chunk_data: Dict[str, Any], embedding: List[float]):
    """
    [US3] Implement save_chunk_to_qdrant function with upsert functionality
    """
    try:
        # Prepare the payload with metadata
        # [US3] Add rich metadata (module, section, URL, chunk ID) to stored embeddings
        payload = {
            'url': chunk_data['url'],
            'module': chunk_data['module'],
            'section': chunk_data['section'],
            'content': chunk_data['content'],
            'title': chunk_data.get('title', ''),
            'created_at': datetime.utcnow().isoformat()
        }

        # Prepare the point to insert
        point = models.PointStruct(
            id=chunk_data['chunk_id'],
            vector=embedding,
            payload=payload
        )

        # Upsert the point (insert or update if exists)
        client.upsert(
            collection_name=collection_name,
            points=[point]
        )

        logger.info(f"Saved chunk {chunk_data['chunk_id']} to Qdrant")
    except Exception as e:
        logger.error(f"Error saving chunk to Qdrant: {e}")
        raise


