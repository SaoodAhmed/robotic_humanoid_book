def get_all_urls(sitemap_url: str) -> List[str]:
    """
    [US1] Implement get_all_urls function to fetch and parse sitemap.xml
    """
    try:
        response = requests.get(sitemap_url)
        response.raise_for_status()

        # Parse the sitemap XML
        root = ET.fromstring(response.content)

        # Extract URLs - handle both regular sitemaps and sitemap indexes
        urls = []
        for url_elem in root.findall('.//{http://www.sitemaps.org/schemas/sitemap/0.9}url/{http://www.sitemaps.org/schemas/sitemap/0.9}loc'):
            urls.append(url_elem.text.strip())

        logger.info(f"Found {len(urls)} URLs in sitemap")
        return urls
    except Exception as e:
        logger.error(f"Error fetching sitemap: {e}")
        raise


def validate_sitemap_url(sitemap_url: str) -> bool:
    """
    [US1] Add sitemap URL validation and error handling
    """
    try:
        # Basic URL format validation
        result = urlparse(sitemap_url)
        if not all([result.scheme, result.netloc]):
            logger.error(f"Invalid URL format: {sitemap_url}")
            return False

        # Test if the sitemap is accessible
        response = requests.head(sitemap_url, timeout=10)
        return response.status_code == 200
    except Exception as e:
        logger.error(f"Error validating sitemap URL {sitemap_url}: {e}")
        return False


def fetch_url_with_retry(url: str, max_retries: int = 3, timeout: int = 10) -> Optional[requests.Response]:
    """
    [US1] Implement URL fetching with retry logic and timeout handling
    """
    for attempt in range(max_retries):
        try:
            response = requests.get(url, timeout=timeout)
            if response.status_code == 200:
                return response
            elif response.status_code == 404:
                logger.warning(f"URL not found (404): {url}")
                return None  # Don't retry 404s
            else:
                logger.warning(f"HTTP {response.status_code} for {url} (attempt {attempt + 1}/{max_retries})")
        except requests.exceptions.Timeout:
            logger.warning(f"Timeout for {url} (attempt {attempt + 1}/{max_retries})")
        except requests.exceptions.RequestException as e:
            logger.warning(f"Request error for {url}: {e} (attempt {attempt + 1}/{max_retries})")

        if attempt < max_retries - 1:
            time.sleep(2 ** attempt)  # Exponential backoff

    logger.error(f"Failed to fetch {url} after {max_retries} attempts")
    return None


def extract_text_from_url(url: str) -> Dict[str, Any]:
    """
    [US2] Implement extract_text_from_url function with BeautifulSoup
    """
    try:
        response = fetch_url_with_retry(url)
        if not response:
            return {
                'url': url,
                'module': '',
                'section': '',
                'content': '',
                'title': ''
            }

        soup = BeautifulSoup(response.content, 'lxml')

        # [US2] Add HTML element removal for navigation, headers, footers, and non-content elements
        for element in soup(['nav', 'header', 'footer', 'aside', 'script', 'style', 'meta', 'link']):
            element.decompose()

        # [US2] Implement Docusaurus-specific CSS selector targeting for main content
        main_content = None
        for selector in ['.main-wrapper', '.container', 'main', '.docContent', '.markdown', '.theme-doc-markdown', '.container.padding-horiz--md']:
            main_content = soup.select_one(selector)
            if main_content:
                break

        # If no specific selector works, use body content
        if not main_content:
            main_content = soup.find('body')

        if main_content:
            # Remove any remaining non-content elements
            for element in main_content(['nav', 'header', 'footer', 'aside', 'script', 'style', 'meta', 'link']):
                element.decompose()

            text = main_content.get_text(separator=' ', strip=True)
        else:
            text = soup.get_text(separator=' ', strip=True)

        # [US2] Add module and section extraction from URL structure
        parsed_url = urlparse(url)
        path_parts = parsed_url.path.strip('/').split('/')

        module = path_parts[0] if path_parts and path_parts[0] else 'home'
        section = path_parts[1] if len(path_parts) > 1 else 'overview'

        return {
            'url': url,
            'module': module,
            'section': section,
            'content': text,
            'title': soup.title.string if soup.title else ''
        }
    except Exception as e:
        logger.error(f"Error extracting content from {url}: {e}")
        return {
            'url': url,
            'module': '',
            'section': '',
            'content': '',
            'title': ''
        }


def clean_content(content: str) -> str:
    """
    [US2] Create content validation and cleanup utilities
    """
    if not content:
        return ""

    # Remove extra whitespace
    import re
    content = re.sub(r'\s+', ' ', content)

    # Remove empty lines
    lines = [line.strip() for line in content.split('\n') if line.strip()]
    cleaned_content = '\n'.join(lines)

    return cleaned_content.strip()


def chunk_text(content: str, chunk_size: int = 1000, overlap: int = 200) -> List[Dict[str, Any]]:
    """
    [US3] Implement chunk_text function for fixed-size chunks with overlap
    """
    if not content:
        return []

    chunks = []
    start = 0

    while start < len(content):
        end = start + chunk_size

        # If this is not the last chunk, try to break at a sentence or word boundary
        if end < len(content):
            # Look for a good break point near the end
            temp_end = end
            while temp_end > start + chunk_size - overlap and temp_end < len(content):
                if content[temp_end] in '.!? \n':
                    end = temp_end + 1
                    break
                temp_end += 1

        chunk_text = content[start:end].strip()
        if chunk_text:  # Only add non-empty chunks
            chunk_id = str(uuid.uuid4())
            chunks.append({
                'chunk_id': chunk_id,
                'content': chunk_text,
                'start_pos': start,
                'end_pos': end
            })

        # Move start position with overlap
        start = end - overlap if end < len(content) else end

        # Prevent infinite loop if chunk_size is too small
        if start == end:
            start += chunk_size

    logger.info(f"Content chunked into {len(chunks)} pieces")
    return chunks


